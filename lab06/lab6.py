# a[i][j]: i - строка, j - столбец. Например, a[1][2] - вторая строка, третий столбец.


def read_matrix():
    m = int(input("Количество строк M = "))
    print("Введите", m, "строк, элементы через пробел:")
    # Матрица - список строк, каждая строка - список чисел.
    a = []
    for i in range(m):
        # Разбиваем введённую строку по пробелам и получаем числа.
        row = [int(x) for x in input().split()]
        a.append(row)
    return a


def print_matrix(a):
    for row in a:
        # Добавляем пробелы слева от чисел, чтобы столбцы стояли ровно.
        print(" ".join(str(x).rjust(4) for x in row))


def task1():
    print("\n1. Вывод квадратной матрицы по спирали против часовой стрелки")
    a = read_matrix()
    m = len(a)
    # Сюда записываем клетки в порядке обхода.
    res = []
    # Границы слоя: верхняя и нижняя строки, левый и правый столбцы.
    top = 0
    bottom = m - 1
    left = 0
    right = m - 1
    # Пока остался хотя бы один слой.
    while top <= bottom:
        # Если края сошлись, осталась только центральная клетка.
        if top == bottom:
            res.append(a[top][left])
            break
        # Идём вниз по левому краю: меняем строку i, столбец left тот же.
        for i in range(top, bottom + 1):
            res.append(a[i][left])
        # Идём вправо по нижнему краю, левый угол уже взяли.
        for j in range(left + 1, right + 1):
            res.append(a[bottom][j])
        # Идём вверх по правому краю, нижний угол уже взяли.
        for i in range(bottom - 1, top - 1, -1):
            res.append(a[i][right])
        # Идём влево по верхнему краю, оба угла уже взяли.
        for j in range(right - 1, left, -1):
            res.append(a[top][j])
        # Сдвигаем все четыре границы на одну клетку внутрь.
        top += 1
        bottom -= 1
        left += 1
        right -= 1
    print(" ".join(str(x) for x in res))


def task2():
    print("\n2. Сумма и произведение элементов K-й строки")
    a = read_matrix()
    k = int(input("K = "))
    # Сумму начинаем с 0, произведение с 1, чтобы не обнулить его.
    s = 0
    p = 1
    # Строка K хранится под индексом k - 1.
    for x in a[k - 1]:
        # Прибавляем число к сумме и умножаем на него произведение.
        s += x
        p *= x
    print("Сумма =", s)
    print("Произведение =", p)


def task3():
    print("\n3. Столбец с наименьшим произведением элементов")
    a = read_matrix()
    # m - число строк, n - длина первой строки, то есть число столбцов.
    m = len(a)
    n = len(a[0])
    # best - индекс нужного столбца; min_p пока неизвестно.
    best = 0
    min_p = None
    # Берём столбцы по одному, слева направо.
    for j in range(n):
        # Для каждого столбца считаем произведение заново.
        p = 1
        # Идём по строкам i, не меняя столбец j.
        for i in range(m):
            p *= a[i][j]
        # Запоминаем первый результат или новый минимум.
        if min_p is None or p < min_p:
            min_p = p
            best = j
    # Переводим индекс в номер столбца: нумерация с 1.
    print("Номер столбца:", best + 1)
    print("Произведение =", min_p)


def task4():
    print("\n4. Количество элементов больше среднего в каждом столбце")
    a = read_matrix()
    m = len(a)
    n = len(a[0])
    # Считаем отдельно для каждого столбца.
    for j in range(n):
        s = 0
        # Складываем числа сверху вниз по столбцу j.
        for i in range(m):
            s += a[i][j]
        # В столбце m чисел, поэтому сумму делим на m.
        avg = s / m
        # Второй раз идём по тому же столбцу и считаем числа выше среднего.
        cnt = 0
        for i in range(m):
            if a[i][j] > avg:
                cnt += 1
        print("Столбец", j + 1, ":", cnt)


def task5():
    print("\n5. Первый столбец, содержащий только нечетные числа")
    a = read_matrix()
    m = len(a)
    n = len(a[0])
    # Если подходящего столбца нет, ответ останется 0.
    res = 0
    # Начинаем слева, чтобы найти именно первый подходящий столбец.
    for j in range(n):
        # Пока не встретили чётное, считаем столбец подходящим.
        odd = True
        for i in range(m):
            # Остаток 0 при делении на 2 значит, что число чётное.
            if a[i][j] % 2 == 0:
                odd = False
                # Одного чётного достаточно, дальше этот столбец не смотрим.
                break
        # Если ни одного чётного не нашли, запоминаем номер и заканчиваем поиск.
        if odd:
            res = j + 1
            break
    print(res)


def task6():
    print("\n6. Поменять местами минимальный и максимальный элемент в каждой строке")
    a = read_matrix()
    # Берём каждую строку отдельно.
    for row in a:
        # min и max находят числа, index - их места в строке.
        i_min = row.index(min(row))
        i_max = row.index(max(row))
        # Меняем местами только эти два числа в строке.
        row[i_min], row[i_max] = row[i_max], row[i_min]
    print_matrix(a)


def task7():
    print("\n7. Поменять местами столбцы с минимальным и максимальным элементом")
    a = read_matrix()
    m = len(a)
    n = len(a[0])
    # Сначала и минимум, и максимум - верхняя левая клетка, столбец 0.
    j_min = 0
    j_max = 0
    mn = a[0][0]
    mx = a[0][0]
    # Проверяем все клетки: i идёт по строкам, j - по столбцам.
    for i in range(m):
        for j in range(n):
            # Нашли число меньше - запоминаем число и его столбец.
            if a[i][j] < mn:
                mn = a[i][j]
                j_min = j
            # Нашли число больше - тоже запоминаем его столбец.
            if a[i][j] > mx:
                mx = a[i][j]
                j_max = j
    # Обмениваем столбцы по клеткам: в каждой строке меняем два числа.
    for i in range(m):
        a[i][j_min], a[i][j_max] = a[i][j_max], a[i][j_min]
    print_matrix(a)


def task8():
    print("\n8. Поменять местами левую верхнюю и правую нижнюю четверти")
    a = read_matrix()
    m = len(a)
    n = len(a[0])
    # hm и hn - половина числа строк и столбцов.
    hm = m // 2
    hn = n // 2
    # Перебираем только верхнюю левую четверть, чтобы не поменять клетки обратно.
    for i in range(hm):
        for j in range(hn):
            # Парная клетка на hm строк ниже и на hn столбцов правее.
            a[i][j], a[i + hm][j + hn] = a[i + hm][j + hn], a[i][j]
    print_matrix(a)


def task9():
    print("\n9. Упорядочить строки по возрастанию первых элементов")
    a = read_matrix()
    m = len(a)
    # Как в сортировке выбором: i - место для следующей строки.
    for i in range(m - 1):
        # Пока считаем, что самое маленькое первое число у строки i.
        k = i
        # Ищем среди строк ниже той, что стоит на i.
        for j in range(i + 1, m):
            # Сравниваем только числа в первом столбце.
            if a[j][0] < a[k][0]:
                k = j
        # Меняем местами целые строки, а не только первые числа.
        a[i], a[k] = a[k], a[i]
    print_matrix(a)


def task10():
    print("\n10. Суммы диагоналей, параллельных главной")
    a = read_matrix()
    m = len(a)
    # d = 0 даёт главную диагональ; d < 0 - ниже неё, d > 0 - выше.
    for d in range(-(m - 1), m):
        s = 0
        # На одной диагонали j - i постоянно: на шаг вниз идёт шаг вправо.
        for i in range(m):
            # Из j - i = d получаем индекс столбца: j = i + d.
            j = i + d
            # Не в каждой строке есть клетка этой диагонали.
            if 0 <= j < m:
                s += a[i][j]
        print("Диагональ", d + m, ":", s)


