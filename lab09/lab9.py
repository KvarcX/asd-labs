def selection_sort(a):
    n = len(a)
    # i - место, куда ставим очередное самое маленькое число.
    for i in range(n - 1):
        # Пока считаем самым маленьким первое число из оставшихся.
        k = i
        # Смотрим остальные числа справа от i.
        for j in range(i + 1, n):
            # Если нашли число меньше, запоминаем его место.
            if a[j] < a[k]:
                k = j
        # Меняем найденное число местами с тем, что стоит на i.
        a[i], a[k] = a[k], a[i]
        # Показываем массив после обмена.
        print("Шаг " + str(i + 1) + " (минимум " + str(a[i]) + "):", a)
    return a


a = [int(x) for x in input("Элементы массива через пробел: ").split()]
print("Исходный массив:", a)
selection_sort(a)
print("Отсортированный массив:", a)
