def insertion_sort(a):
    # Первое число уже на месте, начинаем со второго.
    for i in range(1, len(a)):
        # Запоминаем число для вставки.
        key = a[i]
        # Смотрим на соседа слева.
        j = i - 1
        # Пока слева есть число больше key, сдвигаем его.
        while j >= 0 and a[j] > key:
            # Сдвигаем число вправо.
            a[j + 1] = a[j]
            # Идём на шаг влево.
            j -= 1
        # Вставляем key на освободившееся место.
        a[j + 1] = key
        # Показываем массив после вставки.
        print("Шаг " + str(i) + " (вставили " + str(key) + "):", a)
    return a


a = [int(x) for x in input("Элементы массива через пробел: ").split()]
print("Исходный массив:", a)
insertion_sort(a)
print("Отсортированный массив:", a)
