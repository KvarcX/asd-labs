def binary_search(a, x):
    # Сначала ищем по всему массиву: от первого до последнего элемента.
    left = 0
    right = len(a) - 1
    # Пока между границами есть хотя бы одно число.
    while left <= right:
        # Берём индекс середины без дробной части.
        mid = (left + right) // 2
        print("left =", left, "right =", right, "mid =", mid, "a[mid] =", a[mid])
        # Если нашли число, возвращаем его индекс.
        if a[mid] == x:
            return mid
        # Если число в середине больше x, оставляем только левую часть.
        if a[mid] > x:
            right = mid - 1
        else:
            # Если оно меньше x, оставляем только правую часть.
            left = mid + 1
    # Числа для проверки закончились, x не нашли.
    return -1


a = [int(x) for x in input("Элементы массива через пробел: ").split()]
a.sort()  # бинарный поиск работает только на отсортированном массиве
print("Отсортированный массив:", a)
x = int(input("Что ищем: "))
i = binary_search(a, x)
if i == -1:
    print("Элемент не найден")
else:
    print("Элемент найден, индекс", i)
