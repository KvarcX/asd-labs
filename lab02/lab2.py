def task3():
    print("\n3. Какая из точек B и C ближе к точке A")
    xa = float(input("xA = "))
    ya = float(input("yA = "))
    xb = float(input("xB = "))
    yb = float(input("yB = "))
    xc = float(input("xC = "))
    yc = float(input("yC = "))
    ab = math.sqrt((xb - xa) ** 2 + (yb - ya) ** 2)
    ac = math.sqrt((xc - xa) ** 2 + (yc - ya) ** 2)
    if ab < ac:
        print("Ближе точка B, расстояние =", round(ab, 3))
    elif ac < ab:
        print("Ближе точка C, расстояние =", round(ac, 3))
    else:
        print("Точки B и C на одинаковом расстоянии =", round(ab, 3))


